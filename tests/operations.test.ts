const cleanups: (() => Promise<void> | void)[] = []
afterEach(async () => { for (const cleanup of cleanups.splice(0).reverse()) await cleanup() })
export async function setupOperationFixture(mode: 'confirm-each' | 'time-limited' = 'confirm-each', disk = false, aiOptions?: { provider: 'openai' | 'anthropic'; fetcher: typeof fetch }) {
  const commands: string[] = []
  const remote = await sshFixture({ exec: (command, stream) => {
    commands.push(command)
    const marker = command.match(/[a-f0-9]{48}/)![0]
    stream.write(`${marker}\0/synthetic/confirmed\0`)
    if (command.includes('hold')) return
    if (command.includes('drop')) { stream.end(); return }
    if (command.includes('redact')) { stream.write('target-'); setTimeout(() => { stream.write('secret and done'); stream.exit(0); stream.end() }, 10); return }
    if (command.includes('flood')) { stream.write(Buffer.alloc(1048577, 'a')); return }
    stream.write('hello 🌊\n'); stream.stderr.write('warning\n')
    setTimeout(() => { stream.exit(command.includes('failure') ? 9 : 0); stream.end() }, 10)
  } })
  cleanups.push(() => remote.close())
  const directory = mkdtempSync(join(tmpdir(), 'hostharbor-operation-'))
  cleanups.push(() => rmSync(directory, { recursive: true, force: true }))
  const path = disk ? join(directory, 'test.sqlite') : ':memory:'
  const servers = new ServerService(new Store(path)), key = randomBytes(32)
  servers.unlock(key)
  const credential = servers.saveCredential({ name: 'synthetic credential', kind: 'password', password: 'target-secret' })
  const target = servers.saveServer({ name: 'synthetic target', host: '127.0.0.1', port: remote.port, username: 'target-user', credentialId: credential.id })
  const result = await servers.testConnection(target.id)
  if (result.status !== 'host-key-required') throw new Error('Expected synthetic host challenge')
  servers.trustHost(result.challengeId)
  const ai = aiOptions ? new AiService(servers, 15000, aiOptions.fetcher) : undefined
  if (ai && aiOptions) ai.save({ revision: 0, provider: aiOptions.provider, baseUrl: 'https://synthetic.invalid/v1', apiKey: 'synthetic-ai-key', model: 'synthetic-reviewer' })
  const operations = new OperationService(servers, ai)
  cleanups.push(() => { ai?.close(); operations.close(); servers.close() })
  const access = operations.createProfile({ name: 'synthetic agent', serverIds: [target.id], mode, expiresAt: Date.now() + 60000 })
  const input: CommandInput = { serverId: target.id, requestKey: randomBytes(8).toString('hex'), command: 'hello', cwd: '/synthetic/requested', timeoutMs: 2000, connectTimeoutMs: 2000 }
  if (mode === 'time-limited') operations.policy.save({ revision: 0, mode: 'rules', rules: ['hello', 'hold', 'drop', 'flood', 'redact', 'failure', 'hold synthetic-sensitive-command'].map((command) => ({ id: randomUUID(), name: 'synthetic exact command', enabled: true, action: 'allow', profileIds: [access.profile.id], serverIds: [target.id], command, cwd: null, expiresAt: null })) })
  return { remote, servers, credential, target, operations, access, input, commands, path, key, ai }
}
async function finish(operations: OperationService, id: string): Promise<Operation> {
  await vi.waitFor(() => expect(['succeeded', 'failed', 'unknown', 'interrupted']).toContain(operations.get(id).state), { timeout: 6000 })
  return operations.get(id)
}
